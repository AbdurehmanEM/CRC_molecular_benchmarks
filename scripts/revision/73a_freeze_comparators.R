###############################################################################
# 73a_freeze_comparators.R - Protocol amendment v2.3, PART A (discovery only)
#
# Pre-specified comparators for the frozen panels, selected and fitted on the
# DISCOVERY cohort (GSE178341) only, then frozen with SHA-256 before any
# validation cohort is scored (73b).
#
#   C1_DE    "standard single-cell marker route": the 4 predictor-pool genes most
#            enriched in the program's compartment (donor-level pseudobulk edgeR QL,
#            compartment vs all other profiled compartments, donor as blocking
#            factor; ranked by logFC among genes with logFC > 0). The number of the
#            4 that also meet FDR < 0.05 and logFC > 1 is reported.
#   C2_CORR  the 4 predictor-pool genes with the highest Spearman correlation with
#            the discovery target (equal-weight baseline of protocol v0.7, now frozen
#            on all discovery donors and taken to the external cohorts).
#
# Both: equal-weight mean z-score (discovery mean/SD), linearly calibrated on
# discovery donors (OLS), stored in the same format as the frozen panels so the
# identical prediction and evaluation code is used (panel_predict / eval_program_cohort).
# Pool restriction (both comparators, pre-specified): predictor genes of the program
# (gene partition) whose SYMBOL is present in every main validation cohort for that
# compartment. Only gene presence is used, never validation expression values.
#
# Do NOT edit this file after 73b has been run.
###############################################################################
source("50_revision_config.R"); source("50_revision_helpers.R"); init_revision(); require_gate()
suppressPackageStartupMessages({ library(edgeR); library(digest) })
set.seed(SEED)

FROZEN_COMP_FILE <- file.path(PROJECT_ROOT, "04_processed_data", "frozen_panel", "frozen_comparators_v2.3.rds")
if (file.exists(FROZEN_COMP_FILE)) stop("Comparators already frozen: ", FROZEN_COMP_FILE,
                                        "\nDo not re-run 73a. Delete the file only if 73b has NOT been run.")

## Frozen panels must be untouched
for (k in names(FROZEN_FILES))
  stopifnot(digest(file = FROZEN_FILES[[k]], algo = "sha256") == FROZEN_SHA256[[k]])

panels <- load_panels(); partition <- load_partition()
pc <- program_compartment(panels); cmps <- unique(pc)
lc <- build_lc_cache(c(DISCOVERY, VALIDATION), cmps)
dstat <- all_disc_stats(panels, partition, lc)
symmap <- load_symbol_map(partition, lc[[DISCOVERY]][[cmps[1]]])

## ---- C1: compartment enrichment on discovery raw pseudobulk counts ------------
## All compartments with a counts file, eligible donors only (>= MIN_CELLS cells).
spec <- PB_FILES[[DISCOVERY]]
cnt <- list()
for (cmp in setdiff(names(spec), "type")) {
  o <- readRDS(file.path(PB_DIR, spec[[cmp]]))
  M <- as.matrix(o$counts %||% o)
  M <- .filter_donors(M, o$n_cells, DISCOVERY, cmp, quiet = FALSE)
  colnames(M) <- paste(cmp, colnames(M), sep = "__")
  cnt[[cmp]] <- M
}
genes_all <- Reduce(intersect, lapply(cnt, rownames))
Y <- do.call(cbind, lapply(cnt, function(M) M[genes_all, , drop = FALSE]))
comp_of  <- sub("__.*$", "", colnames(Y))
donor_of <- sub("^[^_]+__", "", colnames(Y))
msg("C1 matrix:", nrow(Y), "genes x", ncol(Y), "profiles;", length(unique(donor_of)), "donors")

de <- list()
for (cmp in cmps) {
  is_t <- factor(comp_of == cmp, levels = c(FALSE, TRUE))
  design <- model.matrix(~ factor(donor_of) + is_t)
  dge <- DGEList(Y)
  keep <- filterByExpr(dge, group = is_t)
  dge <- calcNormFactors(dge[keep, , keep.lib.sizes = FALSE])
  dge <- estimateDisp(dge, design)
  tt <- topTags(glmQLFTest(glmQLFit(dge, design), coef = ncol(design)), n = Inf, sort.by = "none")$table
  de[[cmp]] <- data.table(compartment = cmp, row_id = rownames(tt), symbol = unname(symmap[rownames(tt)]),
                          logFC = tt$logFC, logCPM = tt$logCPM, FDR = tt$FDR)
  msg("C1 DE", cmp, ":", sum(tt$FDR < 0.05 & tt$logFC > 1), "genes FDR<0.05 & logFC>1")
}
de_all <- rbindlist(de)
write_out(de_all, "73a_C1_compartment_DE")

## ---- Pools: predictor genes present (by symbol) in every main validation cohort
pool_for <- function(p) {
  cmp <- pc[[p]]; L <- lc[[DISCOVERY]][[cmp]]
  pool <- partition[program == p & role == "predictor" & row_id %in% rownames(L)]
  for (co in VALIDATION) {
    V <- lc[[co]][[cmp]]
    if (!is.null(V) && ncol(V) >= MIN_DONORS) pool <- pool[symbol %in% rownames(V)]
  }
  pool <- pool[apply(L[pool$row_id, , drop = FALSE], 1, sd) > 1e-8]
  pool$row_id
}

## Equal-weight score in frozen-panel format: intercept + sum((b/k) * z)
ew_panel <- function(genes, L, y) {
  s <- zstats(L[genes, , drop = FALSE])
  score <- colMeans(zapply(L[genes, , drop = FALSE], s))
  f <- lm.fit(cbind(1, score), y)$coefficients
  data.table(row_id = genes, symbol = unname(symmap[genes]), coef = unname(f[2]) / length(genes),
             mu = unname(s$mu), sd = unname(s$sd), intercept = unname(f[1]))
}

comp <- list(); sel_rows <- list()
for (p in names(panels)) {
  cmp <- pc[[p]]; L <- lc[[DISCOVERY]][[cmp]]
  et <- eval_table(p, partition, dstat); y <- target_score(L, et, "row_id")$y
  pool <- pool_for(p); k <- 4
  # C1
  d <- de_all[compartment == cmp & row_id %in% pool & logFC > 0][order(-logFC)]
  g1 <- head(d$row_id, k)
  # C2
  r <- apply(L[pool, , drop = FALSE], 1, function(x) suppressWarnings(cor(x, y, method = "spearman")))
  g2 <- head(names(sort(r[is.finite(r)], decreasing = TRUE)), k)
  comp[[p]] <- list(C1_DE = if (length(g1)) ew_panel(g1, L, y) else NULL,
                    C2_CORR = if (length(g2)) ew_panel(g2, L, y) else NULL)
  frozen_genes <- panels[[p]]$row_id
  sel_rows[[p]] <- data.table(
    program = p, compartment = cmp, pool_size = length(pool), n_disc_donors = ncol(L),
    C1_genes = paste(symmap[g1], collapse = ", "),
    C1_n_FDR05_logFC1 = sum(d[row_id %in% g1, FDR < 0.05 & logFC > 1]),
    C1_overlap_frozen = paste(symmap[intersect(g1, frozen_genes)], collapse = ", "),
    C2_genes = paste(symmap[g2], collapse = ", "),
    C2_overlap_frozen = paste(symmap[intersect(g2, frozen_genes)], collapse = ", "),
    frozen_genes = paste(symmap[frozen_genes], collapse = ", "))
}
sel <- rbindlist(sel_rows)
write_out(sel, "73a_comparator_genes")

## ---- Freeze --------------------------------------------------------------------
saveRDS(list(comparators = comp, selection = sel, de = de_all,
             rules = list(C1 = "top 4 predictor-pool genes by compartment logFC (>0), edgeR QL, donor-blocked, discovery only",
                          C2 = "top 4 predictor-pool genes by Spearman with discovery target",
                          score = "equal-weight mean z (discovery mean/SD), OLS-calibrated on discovery",
                          pool = "predictor genes present by symbol in every main validation cohort (presence only)",
                          missing_gene = "comparator not evaluable in a cohort if any of its genes is absent"),
             created = format(Sys.time()), protocol = "v2.3", seed = SEED,
             frozen_panel_sha256 = FROZEN_SHA256),
        FROZEN_COMP_FILE)
h <- digest(file = FROZEN_COMP_FILE, algo = "sha256")
writeLines(h, sub("\\.rds$", ".sha256", FROZEN_COMP_FILE))
writeLines(capture.output(sessionInfo()), file.path(OUT_DIR, "73a_sessionInfo.txt"))
print(sel[, .(program, pool_size, C1_genes, C1_n_FDR05_logFC1, C2_genes)])
cat("\nFROZEN comparators SHA-256:\n  ", h,
    "\nRecord this hash and today's date in protocol v2.3 BEFORE running 73b_score_comparators.R.\n")
